#!/usr/bin/env python3
"""Generate a typed, zero-dependency client (Python + TypeScript) from an
OpenAPI 3.x spec you legitimately hold: your own API, a customer's API they
mandated you to document, or a public API whose terms allow it.

Input : openapi.json (or .yaml if PyYAML is installed), or a Contour model.json
Output: client.py (stdlib only) + client.ts (native fetch)

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path

HTTP_METHODS = ("get", "post", "put", "patch", "delete", "head", "options")
HEADER = "Generated by Contour (https://github.com/CodeNoLimits/aura51-reversai-contour)"
_TS_RESERVED = set(
    "break case catch class const continue debugger default delete do else enum export extends false finally for "
    "function if import in instanceof new null return super switch this throw true try typeof var void while with "
    "yield let static implements interface package private protected public await".split()
)


def load_spec(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() in (".yaml", ".yml"):
        try:
            import yaml  # optional
        except ImportError:
            sys.exit("[sdkgen] .yaml given but PyYAML is not installed. pip install pyyaml, or convert to .json.")
        return yaml.safe_load(text)
    return json.loads(text)


# --- names -------------------------------------------------------------------
def ident(name: str) -> str:
    """A name that is a valid parameter in both Python and TypeScript."""
    s = re.sub(r"\W", "_", str(name), flags=re.ASCII) or "param"
    if s[0].isdigit():
        s = "_" + s
    if keyword.iskeyword(s) or s in _TS_RESERVED or s in ("self", "body"):
        s += "_"
    return s


def _unique(name: str, used: set[str]) -> str:
    out, n = name, 2
    while out in used:
        out, n = f"{name}_{n}", n + 1
    used.add(out)
    return out


def op_name(method: str, path: str, op: dict) -> str:
    """operationId when present, else a readable name from method + path."""
    if op.get("operationId"):
        raw = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", str(op["operationId"]))
    else:
        parts = [f"by_{p[1:-1]}" if p.startswith("{") else p for p in path.split("/") if p]
        raw = method + "_" + "_".join(parts or ["root"])
    s = re.sub(r"[^0-9a-zA-Z]+", "_", raw).strip("_").lower() or f"{method}_op"
    if s[0].isdigit():
        s = "_" + s
    return s + "_" if keyword.iskeyword(s) else s


def _camel(s: str) -> str:
    parts = [p for p in s.split("_") if p]
    return (parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])) if parts else "op"


def _pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9a-zA-Z]+", str(s)) if p) or "T"


# --- spec walking --------------------------------------------------------------
def _resolve(spec: dict, node: object) -> dict:
    """Follow local $refs (#/components/...). Anything else becomes {}."""
    for _ in range(20):
        if not isinstance(node, dict) or "$ref" not in node:
            break
        ref = node["$ref"]
        target: object = spec
        if not isinstance(ref, str) or not ref.startswith("#/"):
            return {}
        for part in ref[2:].split("/"):
            part = part.replace("~1", "/").replace("~0", "~")
            target = target.get(part) if isinstance(target, dict) else None
        node = target
    return node if isinstance(node, dict) else {}


def _json_schema(spec: dict, holder: object) -> dict | None:
    content = _resolve(spec, holder).get("content") or {}
    for mime, media in content.items():
        if "json" in mime and isinstance(media, dict) and media.get("schema") is not None:
            return media["schema"]
    return None


def iter_ops(spec: dict):
    for path, item in (spec.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        for method, op in item.items():
            if method.lower() in HTTP_METHODS and isinstance(op, dict):
                yield method.lower(), path, op, item


def _operations(spec: dict) -> list[dict]:
    used: set[str] = set()
    ops = []
    for method, path, op, item in iter_ops(spec):
        params: dict[tuple, dict] = {}  # operation-level parameters override path-level ones
        for p in list(item.get("parameters") or []) + list(op.get("parameters") or []):
            p = _resolve(spec, p)
            if isinstance(p.get("name"), str):
                params[(p.get("in"), p["name"])] = p
        names: set[str] = set()
        path_params = [(raw, _unique(ident(raw), names)) for raw in re.findall(r"\{([^}]+)\}", path)]
        query = [(name, _unique(ident(name), names), p.get("schema")) for (where, name), p in params.items() if where == "query"]
        responses = op.get("responses") or {}
        ok = sorted((code for code in responses if str(code).startswith("2")), key=str)
        name = _unique(op_name(method, path, op), used)
        summary = str(op.get("summary") or op.get("description") or "").strip().split("\n")[0]
        if "x-contour-confidence" in op:
            summary = f"{summary + ' — ' if summary else ''}seen {op.get('x-contour-seen')}x, confidence {op['x-contour-confidence']}"
        ops.append(
            {
                "method": method,
                "path": path,
                "name": name,
                "type": _pascal(name),
                "path_params": path_params,
                "query": query,
                "body": bool(op.get("requestBody")),
                "req_schema": _json_schema(spec, op.get("requestBody")),
                "res_schema": _json_schema(spec, responses[ok[0]]) if ok else None,
                "doc": f"{method.upper()} {path}" + (f" — {summary}" if summary else ""),
            }
        )
    return ops


def base_url(spec: dict) -> str:
    servers = spec.get("servers") or []
    if servers and isinstance(servers[0], dict) and servers[0].get("url"):
        return servers[0]["url"].rstrip("/")
    return "https://api.example.com"


def _types(schema: dict) -> list:
    t = schema.get("type")
    types = list(t) if isinstance(t, list) else [t]
    if schema.get("nullable") is True and "null" not in types:
        types.append("null")
    return types


# --- TypeScript ----------------------------------------------------------------
def ts_type(spec: dict, schema: object, depth: int = 0) -> str:
    s = _resolve(spec, schema)
    if not s or depth > 8:
        return "unknown"
    if isinstance(s.get("enum"), list) and s["enum"] and all(isinstance(v, (str, int, float, bool)) for v in s["enum"]):
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key, sep in (("oneOf", " | "), ("anyOf", " | "), ("allOf", " & ")):
        if isinstance(s.get(key), list) and s[key]:
            return sep.join(f"({ts_type(spec, x, depth + 1)})" for x in s[key])
    parts = []
    for t in _types(s):
        if t == "object" or (t is None and "properties" in s):
            props = s.get("properties") or {}
            if props:
                req = set(s.get("required") or [])
                fields = []
                for k, v in props.items():
                    key = k if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", k) else json.dumps(k)
                    fields.append(f"{key}{'' if k in req else '?'}: {ts_type(spec, v, depth + 1)}")
                parts.append("{ " + "; ".join(fields) + " }")
            else:
                extra = s.get("additionalProperties")
                parts.append(f"Record<string, {ts_type(spec, extra, depth + 1) if isinstance(extra, dict) else 'unknown'}>")
        elif t == "array":
            parts.append(f"Array<{ts_type(spec, s.get('items'), depth + 1)}>")
        elif t in ("integer", "number"):
            parts.append("number")
        elif t in ("string", "boolean", "null"):
            parts.append(t)
        else:
            parts.append("unknown")
    return " | ".join(dict.fromkeys(parts))


def gen_typescript(spec: dict, ops: list[dict] | None = None) -> str:
    ops = _operations(spec) if ops is None else ops
    title = " ".join(str((spec.get("info") or {}).get("title") or "").split()) or "API"
    L = [f"// {title} client. {HEADER}. Native fetch, zero dependencies.", ""]
    for op in ops:
        if op["req_schema"] is not None:
            L.append(f"export type {op['type']}Request = {ts_type(spec, op['req_schema'])};")
        if op["res_schema"] is not None:
            L.append(f"export type {op['type']}Response = {ts_type(spec, op['res_schema'])};")
    L += [
        "",
        "export interface ClientOptions { baseUrl?: string; token?: string; headers?: Record<string, string>; }",
        "",
        "export class ApiError extends Error {",
        "  status: number;",
        "  body: string;",
        "  constructor(status: number, body: string) {",
        "    super(`HTTP ${status}: ${body.slice(0, 200)}`);",
        "    this.status = status;",
        "    this.body = body;",
        "  }",
        "}",
        "",
        "export class Client {",
        "  baseUrl: string;",
        "  token?: string;",
        "  headers: Record<string, string>;",
        "",
        "  constructor(o: ClientOptions = {}) {",
        f"    this.baseUrl = (o.baseUrl ?? {json.dumps(base_url(spec))}).replace(/\\/$/, '');",
        "    this.token = o.token;",
        "    this.headers = o.headers ?? {};",
        "  }",
        "",
        "  private async _request(method: string, path: string, query?: Record<string, unknown>, body?: unknown): Promise<any> {",
        "    let url = this.baseUrl + path;",
        "    if (query) {",
        "      const q = new URLSearchParams();",
        "      for (const [k, v] of Object.entries(query)) if (v !== undefined && v !== null) q.append(k, String(v));",
        "      const s = q.toString();",
        "      if (s) url += '?' + s;",
        "    }",
        "    const h: Record<string, string> = { Accept: 'application/json', ...this.headers };",
        "    if (body !== undefined) h['Content-Type'] = 'application/json';",
        "    if (this.token) h['Authorization'] = `Bearer ${this.token}`;",
        "    const res = await fetch(url, { method, headers: h, body: body !== undefined ? JSON.stringify(body) : undefined });",
        "    const txt = await res.text();",
        "    if (!res.ok) throw new ApiError(res.status, txt);",
        "    return txt ? JSON.parse(txt) : null;",
        "  }",
        "",
    ]
    for op in ops:
        params = [f"{py}: string | number" for _, py in op["path_params"]]
        params += [f"{py}?: {ts_type(spec, schema) if schema else 'string'}" for _, py, schema in op["query"]]
        if op["body"]:
            params.append(f"body?: {op['type'] + 'Request' if op['req_schema'] is not None else 'unknown'}")
        route = op["path"].replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
        for raw, py in op["path_params"]:
            route = route.replace("{" + raw + "}", "${encodeURIComponent(String(" + py + "))}")
        query = "{ " + ", ".join(f"{json.dumps(raw)}: {py}" for raw, py, _ in op["query"]) + " }" if op["query"] else "undefined"
        ret = op["type"] + "Response" if op["res_schema"] is not None else "unknown"
        L.append(f"  /** {op['doc'].replace('*/', '* /')} */")
        L.append(f"  {_camel(op['name'])}({', '.join(params)}): Promise<{ret}> {{")
        L.append(f"    return this._request({json.dumps(op['method'].upper())}, `{route}`, {query}, {'body' if op['body'] else 'undefined'});")
        L.append("  }")
        L.append("")
    L.append("}")
    return "\n".join(L) + "\n"


# --- Python --------------------------------------------------------------------
class _PyTypes:
    """Turns schemas into annotations, emitting a TypedDict per object shape."""

    def __init__(self, spec: dict):
        self.spec, self.lines, self.names = spec, [], set()

    def type(self, schema: object, hint: str, depth: int = 0) -> str:
        s = _resolve(self.spec, schema)
        if not s or depth > 8:
            return "Any"
        if isinstance(s.get("enum"), list) and s["enum"] and all(isinstance(v, (str, int, bool)) for v in s["enum"]):
            return f"Literal[{', '.join(repr(v) for v in s['enum'])}]"
        for key in ("oneOf", "anyOf"):
            if isinstance(s.get(key), list) and s[key]:
                return f"Union[{', '.join(self.type(x, f'{hint}{i}', depth + 1) for i, x in enumerate(s[key]))}]"
        parts = []
        for t in _types(s):
            if t == "object" or (t is None and "properties" in s):
                if s.get("properties"):
                    parts.append(self._typeddict(s, hint, depth))
                else:
                    extra = s.get("additionalProperties")
                    parts.append(f"Dict[str, {self.type(extra, hint + 'Value', depth + 1) if isinstance(extra, dict) else 'Any'}]")
            elif t == "array":
                parts.append(f"List[{self.type(s.get('items'), hint + 'Item', depth + 1)}]")
            elif t in ("integer", "number", "string", "boolean"):
                parts.append({"integer": "int", "number": "float", "string": "str", "boolean": "bool"}[t])
            elif t == "null":
                parts.append("None")
            else:
                parts.append("Any")
        parts = list(dict.fromkeys(parts))
        if "None" in parts and len(parts) > 1:
            parts.remove("None")
            inner = parts[0] if len(parts) == 1 else f"Union[{', '.join(parts)}]"
            return f"Optional[{inner}]"
        return parts[0] if len(parts) == 1 else f"Union[{', '.join(parts)}]"

    def _typeddict(self, s: dict, hint: str, depth: int) -> str:
        name = _unique(_pascal(hint), self.names)
        req = set(s.get("required") or [])
        fields = [(k, self.type(v, hint + _pascal(k), depth + 1), k in req) for k, v in s["properties"].items()]
        if not all(k.isidentifier() and not keyword.iskeyword(k) for k, _, _ in fields):
            body = ", ".join(f"{k!r}: {t!r}" for k, t, _ in fields)
            self.lines += [f"{name} = TypedDict({name!r}, {{{body}}}, total=False)", "", ""]
            return name
        required = [f"    {k}: {t}" for k, t, r in fields if r]
        optional = [f"    {k}: {t}" for k, t, r in fields if not r]
        if required and optional:
            self.lines += [f"class _{name}Required(TypedDict):", *required, "", ""]
            self.lines += [f"class {name}(_{name}Required, total=False):", *optional, "", ""]
        else:
            total = "" if required else ", total=False"
            self.lines += [f"class {name}(TypedDict{total}):", *(required or optional), "", ""]
        return name


def _py_doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def gen_python(spec: dict, ops: list[dict] | None = None) -> str:
    ops = _operations(spec) if ops is None else ops
    title = " ".join(str((spec.get("info") or {}).get("title") or "").split()) or "API"
    types = _PyTypes(spec)
    methods = []
    for op in ops:
        args = ["self"] + [f"{py}: Union[str, int]" for _, py in op["path_params"]]
        args += [f"{py}: Optional[{types.type(schema, op['type'] + _pascal(py)) if schema else 'str'}] = None" for _, py, schema in op["query"]]
        if op["body"]:
            req = types.type(op["req_schema"], op["type"] + "Request") if op["req_schema"] is not None else "Any"
            args.append(f"body: Optional[{req}] = None")
        ret = types.type(op["res_schema"], op["type"] + "Response") if op["res_schema"] is not None else "Any"
        route = op["path"]
        for raw, py in op["path_params"]:
            route = route.replace("{" + raw + "}", "\0" + py + "\1")
        route = repr(route.replace("{", "{{").replace("}", "}}")).replace("\\x00", "{_q(").replace("\\x01", ")}")
        query = "{" + ", ".join(f"{raw!r}: {py}" for raw, py, _ in op["query"]) + "}" if op["query"] else "None"
        methods += [
            f"    def {op['name']}({', '.join(args)}) -> {ret}:",
            f'        """{_py_doc(op["doc"])}"""',
            f"        return {'' if ret == 'Any' else f'cast({ret!r}, '}self._request({op['method'].upper()!r}, {'f' if op['path_params'] else ''}{route}, query={query}, body={'body' if op['body'] else 'None'}){'' if ret == 'Any' else ')'}",
            "",
        ]
    L = [
        f'"""{_py_doc(title)} client. {HEADER}. Standard library only."""',
        "from __future__ import annotations",
        "",
        "import json",
        "import urllib.error",
        "import urllib.parse",
        "import urllib.request",
        "from typing import Any, Dict, List, Literal, Optional, TypedDict, Union, cast",
        "",
        "",
        "def _q(value: Union[str, int]) -> str:",
        "    return urllib.parse.quote(str(value), safe='')",
        "",
        "",
        *types.lines,
        "class ApiError(Exception):",
        "    def __init__(self, status: int, body: str):",
        "        super().__init__(f'HTTP {status}: {body[:200]}')",
        "        self.status, self.body = status, body",
        "",
        "",
        "class Client:",
        f"    def __init__(self, base_url: str = {base_url(spec)!r}, token: Optional[str] = None, headers: Optional[Dict[str, str]] = None):",
        "        self.base_url = base_url.rstrip('/')",
        "        self.token = token",
        "        self.headers = headers or {}",
        "",
        "    def _request(self, method: str, path: str, query: Optional[Dict[str, Any]] = None, body: Any = None) -> Any:",
        "        url = self.base_url + path",
        "        if query:",
        "            q = {k: v for k, v in query.items() if v is not None}",
        "            if q:",
        "                url += '?' + urllib.parse.urlencode(q)",
        "        data = json.dumps(body).encode() if body is not None else None",
        "        h = {'Accept': 'application/json', **self.headers}",
        "        if body is not None:",
        "            h['Content-Type'] = 'application/json'",
        "        if self.token:",
        "            h['Authorization'] = f'Bearer {self.token}'",
        "        req = urllib.request.Request(url, data=data, headers=h, method=method)",
        "        try:",
        "            with urllib.request.urlopen(req, timeout=60) as r:",
        "                raw = r.read().decode()",
        "                return json.loads(raw) if raw else None",
        "        except urllib.error.HTTPError as e:",
        "            raise ApiError(e.code, e.read().decode()) from None",
        "",
        *methods,
    ]
    return "\n".join(L).rstrip("\n") + "\n"


def generate(spec: dict) -> tuple[str, str, int]:
    ops = _operations(spec)
    return gen_python(spec, ops), gen_typescript(spec, ops), len(ops)


def main() -> None:
    ap = argparse.ArgumentParser(description="Contour sdkgen: OpenAPI -> typed client.py + client.ts")
    ap.add_argument("spec", help="openapi.json (or .yaml with PyYAML)")
    ap.add_argument("--out", default="./sdk_out", help="Output directory")
    args = ap.parse_args()

    p = Path(args.spec)
    if not p.exists():
        sys.exit(f"[sdkgen] Spec not found: {p}")
    spec = load_spec(p)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    py, ts, n = generate(spec)
    (out / "client.py").write_text(py, encoding="utf-8")
    (out / "client.ts").write_text(ts, encoding="utf-8")
    print(f"[sdkgen] {n} operations")
    print(f"[sdkgen] -> {out / 'client.py'}")
    print(f"[sdkgen] -> {out / 'client.ts'}")


if __name__ == "__main__":
    main()
